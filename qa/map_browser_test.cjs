const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 1500, height: 1100}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  try {
    await page.goto('http://localhost:8080/map/', {waitUntil: 'networkidle'});
    await page.locator('.state-outline').first().waitFor();
    assert.equal(await page.locator('.state-outline').count(), 27);
    assert.equal(await page.locator('.map-bubble').count(), 0);
    await page.getByRole('button', {name: 'Authorize API'}).click();
    const frame = page.frameLocator('#auth-frame');
    await frame.getByRole('button', {name: 'Authorize', exact: true}).first().click();
    await frame.locator('.auth-container input').nth(0).fill('qa-client');
    await frame.locator('.auth-container input').nth(1).fill('QaRotatedPass1!');
    await frame.locator('.auth-btn-wrapper button').filter({hasText: /^Authorize$/}).click();
    await page.locator('#auth-dialog').waitFor({state: 'hidden'});
    await page.waitForFunction(() => document.getElementById('mapped').textContent === '430', {timeout: 30000});
    assert.ok(await page.locator('.map-cluster').count() > 0);
    await page.locator('#cluster').uncheck();
    assert.equal(await page.locator('.map-bubble').count(), 430);
    const initial = await page.locator('#map-world').getAttribute('transform');
    await page.getByRole('button', {name: 'Zoom in', exact: true}).click();
    assert.notEqual(await page.locator('#map-world').getAttribute('transform'), initial);
    await page.getByRole('button', {name: 'Zoom out', exact: true}).click();
    await page.getByRole('button', {name: 'Fit Brazil', exact: true}).click();
    await page.locator('#viewport').check();
    const visibleResponse = page.waitForResponse(response => response.url().includes('/api/v1/demographics/map/?') && new URL(response.url()).searchParams.has('bbox'));
    await page.getByRole('button', {name: 'Zoom in', exact: true}).click();
    const visible = await (await visibleResponse).json();
    assert.ok(visible.count > 0 && visible.count < 430);
    await page.waitForFunction(expected => Number(document.getElementById('mapped').textContent) === expected, visible.count);
    await page.locator('#viewport').uncheck();
    await page.getByRole('button', {name: 'Fit Brazil', exact: true}).click();
    await page.locator('#apply').click();
    await page.waitForFunction(() => document.getElementById('mapped').textContent === '430');
    fs.mkdirSync('/artifacts', {recursive: true});
    await page.screenshot({path: '/artifacts/audience-map-desktop.png', fullPage: true});
    await page.locator('#income-min').fill('3000'); await page.locator('#income-max').fill('4000');
    await page.locator('#apply').click();
    await page.waitForFunction(() => !document.getElementById('apply').disabled);
    let count = Number(await page.locator('#mapped').textContent());
    assert.ok(count > 0 && count < 430);
    await page.locator('#location-list button').first().click();
    await page.locator('#location-detail').getByText(/SHA-256:/).first().waitFor();
    assert.match(await page.locator('#location-detail').textContent(), /locality summary/);
    await page.locator('#income-min').fill(''); await page.locator('#income-max').fill('');
    await page.locator('#age-min').fill('6'); await page.locator('#age-max').fill('10'); await page.locator('#estimate').check();
    await page.locator('#event').selectOption({label: 'QA event - Sao Paulo'});
    await page.locator('#radius').selectOption('25');
    await page.locator('#apply').click();
    await page.waitForFunction(() => !document.getElementById('apply').disabled);
    count = Number(await page.locator('#mapped').textContent());
    assert.ok(count > 0 && count < 430);
    assert.equal(await page.locator('.event-pin').count(), 1);
    assert.match(await page.locator('#map-subtitle').textContent(), /QA event/);
    await page.locator('#location-list button').first().click();
    assert.match(await page.locator('#location-detail').textContent(), /≈/);
    await page.locator('#age-min').fill('0'); await page.locator('#age-max').fill('3');
    await page.locator('#apply').click();
    await page.waitForFunction(() => !document.getElementById('apply').disabled);
    assert.ok(await page.locator('.map-bubble.density-unknown').count() > 0);
    await page.setViewportSize({width: 390, height: 844});
    await page.evaluate(() => window.scrollTo(0, 0));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path: '/artifacts/audience-map-mobile.png', fullPage: true});
    await page.getByRole('button', {name: 'Disconnect', exact: true}).click();
    assert.equal(await page.locator('.map-bubble').count(), 0);
    assert.equal(await page.locator('.event-pin').count(), 0);
    assert.equal(await page.evaluate(() => localStorage.length+sessionStorage.length), 0);
    assert.deepEqual(errors, []);
    console.log('PASS: 27 state outlines, 430 bubbles, Swagger authorization, zoom, income filters, event distance, partial/birth-gap age cohorts, lineage, mobile and logout.');
  } catch (error) {
    fs.mkdirSync('/artifacts', {recursive: true});
    await page.screenshot({path: '/artifacts/audience-map-failure.png', fullPage: true});
    console.error((await page.locator('body').innerText()).slice(0, 3500)); console.error(errors); throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error.message); process.exit(1); });
