const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1100}, acceptDownloads: true});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  try {
    await page.goto('http://localhost:8080/', {waitUntil: 'networkidle'});
    await page.getByRole('heading', {name: 'Find the people behind the places.'}).waitFor();
    await page.getByRole('button', {name: 'Authorize API'}).click();
    const frame = page.frameLocator('#auth-frame');
    await frame.getByRole('button', {name: 'Authorize', exact: true}).first().click();
    await frame.locator('.auth-container input').nth(0).fill('qa-client');
    await frame.locator('.auth-container input').nth(1).fill('QaRotatedPass1!');
    await frame.locator('.auth-btn-wrapper button').filter({hasText: /^Authorize$/}).click();
    await page.locator('#auth-dialog').waitFor({state: 'hidden', timeout: 15000});
    await page.locator('#results-body tr').first().waitFor({timeout: 15000});
    assert.equal(await page.locator('#metric-locations').textContent(), '96');
    assert.match(await page.locator('#results-title').textContent(), /ages 4–8/);
    assert.equal(await page.locator('#results-body tr').count(), 15);
    assert.match(await page.locator('#results-body').textContent(), /Exact band match/);
    fs.mkdirSync('/artifacts', {recursive: true});
    await page.screenshot({path: '/artifacts/frontend-desktop.png', fullPage: true});
    await page.locator('.row-detail').first().click();
    await page.locator('#detail-content').getByText(/SHA-256:/).waitFor();
    assert.match(await page.locator('#detail-content').textContent(), /4–8/);
    await page.locator('#close-detail').click();
    await page.locator('#age-min').fill('6');
    await page.locator('#age-max').fill('10');
    await page.locator('#search-button').click();
    await page.getByRole('heading', {name: 'Districts · ages 6–10'}).waitFor();
    assert.match(await page.locator('#results-body').textContent(), /Bounded count/);
    await page.locator('#estimate').check();
    await page.locator('#search-button').click();
    await page.locator('#results-body').getByText('Proportional estimate').first().waitFor();
    await page.locator('#age-min').fill('0');
    await page.locator('#age-max').fill('3');
    await page.locator('#search-button').click();
    await page.getByRole('heading', {name: 'Districts · ages 0–3'}).waitFor();
    assert.match(await page.locator('#results-body').textContent(), /Not fully covered/);
    assert.match(await page.locator('#notice').textContent(), /Births after/);
    await page.locator('#level').selectOption('neighborhood');
    await page.locator('#search-button').click();
    await page.getByRole('heading', {name: 'No data for this geography'}).waitFor();
    assert.equal(await page.locator('#table-wrap').isVisible(), false);
    await page.locator('#reset').click();
    await page.locator('#search-button').click();
    await page.getByRole('heading', {name: 'Districts · ages 4–8'}).waitFor();
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#export').click();
    const download = await downloadPromise;
    await download.saveAs('/artifacts/cohort-results.csv');
    const csv = fs.readFileSync('/artifacts/cohort-results.csv', 'utf8');
    assert.match(csv, /calendar_year_cohort_shift_v1/);
    assert.equal(csv.trim().split('\r\n').length, 97);
    await page.locator('#coverage-nav').click();
    await page.getByRole('heading', {name: 'Coverage & reference'}).waitFor();
    await page.locator('.coverage-item').first().waitFor();
    await page.setViewportSize({width: 390, height: 844});
    await page.locator('#explorer-nav').isVisible();
    await page.evaluate(() => window.scrollTo(0, 0));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({path: '/artifacts/frontend-mobile.png', fullPage: true});
    await page.reload({waitUntil: 'networkidle'});
    assert.equal(await page.locator('#authorize').isVisible(), true);
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
    assert.deepEqual(errors, []);
    console.log('PASS: real Swagger authorization, exact/partial/birth-gap searches, source details, CSV, coverage, mobile layout and memory-only session.');
  } catch (error) {
    fs.mkdirSync('/artifacts', {recursive: true});
    await page.screenshot({path: '/artifacts/frontend-failure.png', fullPage: true});
    console.error('Visible page state:', (await page.locator('body').innerText()).slice(0, 4500));
    console.error('Browser errors:', errors);
    throw error;
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error.message); process.exit(1); });
